(* {2 Q9 — round trip} *)

let q9 () =
  test "Q9: 44.1 -> 48 -> 44.1 round-trip SNR" (fun () ->
      let rng = Random.State.make [|0x51ab|] in
      let sr = 44100 in
      let n = sr in
      let freqs =
        List.init 20 (fun _ -> 100. +. Random.State.float rng 18000.)
      in
      let phases =
        List.map (fun _ -> Random.State.float rng (2. *. pi)) freqs
      in
      let x =
        Array.init n (fun i ->
            let t = Float.of_int i /. Float.of_int sr in
            List.fold_left2
              (fun acc f ph ->
                acc +. (0.05 *. Float.sin ((2. *. pi *. f *. t) +. ph)) )
              0. freqs phases )
      in
      let up = cfg (44100, 48000) and down = cfg (48000, 44100) in
      List.iter
        (fun s ->
          List.iter
            (fun p ->
              let limit = match p with F64 -> 110. | F32 -> 100. in
              let mid = convert s p up x in
              let y = convert s p down mid in
              if Array.length y <> n then
                failf "%s %s: round trip length %d <> %d" s.sname (pname p)
                  (Array.length y) n ;
              let i0 = n / 10 in
              let sig_p = ref 0. and err_p = ref 0. in
              for i = i0 to n - i0 - 1 do
                sig_p := !sig_p +. (x.(i) *. x.(i)) ;
                let e = x.(i) -. y.(i) in
                err_p := !err_p +. (e *. e)
              done ;
              let snr = 10. *. Float.log10 (!sig_p /. !err_p) in
              if snr < limit then
                failf "%s %s: round-trip SNR %.1f dB < %.0f" s.sname (pname p)
                  snr limit )
            precs )
        surfaces )

(* {2 Q10 — the standard-rate matrix} *)

let standard_rates =
  [8000; 11025; 16000; 22050; 24000; 32000; 44100; 48000; 88200; 96000; 192000]

let ulp64 = Float.ldexp 1. (-52)

let q10 () =
  test "Q10: Q1-Q4 hold over all 110 standard-rate pairs" (fun () ->
      List.iter
        (fun sr ->
          List.iter
            (fun target ->
              if sr <> target then begin
                let c = cfg (sr, target) in
                let l = (Resample.Config.rate c).Pipeline.Rate.num in
                let k = Resample.Config.latency c in
                (* memory guard at the documented creation budget (8 MB). The
                   quantity is the single-stage bank formula over the composite
                   L and K — exact for single-stage plans, an upper proxy for
                   cascades (their composite K folds both stage delays over one
                   L while the real footprint is two far smaller banks, enforced
                   per stage at create; worst standard-rate proxy: 11025 ->
                   192000 at 4.3 MB). *)
                let bank_bytes = l * ((2 * k) + 1) * 8 in
                if bank_bytes > 8 * 1024 * 1024 then
                  failf "%d->%d: bank %d bytes > 8 MB" sr target bank_bytes ;
                let nyq = Float.of_int (Stdlib.min sr target) /. 2. in
                (* Q1/Q2 at scaled tone positions (the 1/5/10/17 kHz set as
                   fractions of the lower Nyquist) *)
                List.iter
                  (fun frac ->
                    let f = frac *. nyq in
                    let y = convert c_path F64 c (tone ~sr ~f ~seconds:1.) in
                    let mags = spectrum y in
                    let d = sfdr mags and t = thdn mags in
                    if d < 130. then
                      failf "%d->%d %g Hz: SFDR %.1f dB < 130" sr target f d ;
                    if t > -125. then
                      failf "%d->%d %g Hz: THD+N %.1f dB > -125" sr target f t )
                  [0.045; 0.23; 0.45; 0.79] ;
                (* Q4 flatness *)
                List.iter
                  (fun frac ->
                    let f = frac *. nyq in
                    let y = convert c_path F64 c (tone ~sr ~f ~seconds:1.) in
                    let dev =
                      Float.abs (20. *. Float.log10 (amp_at ~sr:target ~f y))
                    in
                    if dev > 0.01 then
                      failf "%d->%d %g Hz: gain off by %.4f dB > 0.01" sr target
                        f dev )
                  [0.02; 0.5; 0.913] ;
                (* the GEMM surface stays bound to the executor here too *)
                let f = 0.23 *. nyq in
                let x = tone ~sr ~f ~seconds:1. in
                let a = convert c_path F64 c x in
                let b = convert (List.nth surfaces 1) F64 c x in
                let peak =
                  Array.fold_left (fun m v -> Float.max m (Float.abs v)) 0. a
                in
                let worst = ref 0. in
                Array.iteri
                  (fun i v ->
                    let d = Float.abs (v -. b.(i)) in
                    if d > !worst then worst := d )
                  a ;
                (* The divergence grows with the reduced filter's length:
                   measured worst across the matrix is 26 ULP of peak at 192000
                   -> 24000 (1515 taps; about -290 dBFS). Gate at the next power
                   of two. *)
                if !worst > 32. *. peak *. ulp64 then
                  failf "%d->%d: GEMM diverges by %.1f ULP of peak" sr target
                    (!worst /. (peak *. ulp64))
              end )
            standard_rates )
        standard_rates )

