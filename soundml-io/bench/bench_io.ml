(* soundml-io benchmarks.

   Audio-file decode and encode over the deterministic corpus of [Io_corpus]
   (generated by soundml-io's own writer on first use, so the C ceiling harness
   in [bench_sndfile.c] and the Python cross-reference in [bench_soundml_io.py]
   read identical bytes). Row classes, per the io performance gates: whole-file
   reads per format family at both size classes; the header probe; the
   many-small-files ingest loop; chunked writes; and the fused resampled read
   next to its honest decomposition (native read plus [Resample.apply], config
   built per call on both sides, the way a caller would write it). *)

let io_ok ~what = function
  | Ok v ->
      v
  | Error e ->
      failwith (Stdlib.Format.asprintf "%s: %a" what Soundml_io.pp_error e)

let io_formats =
  ["wav-pcm16"; "wav-pcm24"; "wav-pcm32"; "wav-float32"; "flac"; "ogg"]

let io_read_benchmarks () =
  List.concat_map
    (fun label ->
      let small = Io_corpus.small label
      and bulk = Io_corpus.bulk label
      and bulk_mono = Io_corpus.bulk_mono label in
      [ Thumper.bench (Printf.sprintf "read %s 1s f32" label) (fun () ->
            io_ok ~what:label (Soundml_io.read Nx.float32 small) )
      ; Thumper.bench (Printf.sprintf "read %s 30s f32" label) (fun () ->
            io_ok ~what:label (Soundml_io.read Nx.float32 bulk) )
      ; Thumper.bench (Printf.sprintf "read %s 30s-mo f32" label) (fun () ->
            io_ok ~what:label (Soundml_io.read Nx.float32 bulk_mono) ) ] )
    io_formats

let io_info_benchmarks () =
  List.map
    (fun label ->
      let bulk = Io_corpus.bulk label in
      Thumper.bench (Printf.sprintf "open_info %s" label) (fun () ->
          io_ok ~what:label (Soundml_io.info bulk) ) )
    ["wav-pcm16"; "flac"; "ogg"]

let io_many_benchmarks () =
  List.concat_map
    (fun label ->
      let paths = Io_corpus.many label in
      (* the allocating ingest loop (librosa's own shape) *)
      [ Thumper.bench (Printf.sprintf "many 1000x1s %s f32" label) (fun () ->
            List.iter
              (fun p ->
                ignore
                  ( io_ok ~what:label (Soundml_io.read Nx.float32 p)
                    : _ Soundml_io.audio ) )
              paths ) ] )
    Io_corpus.many_classes

let io_write_benchmarks () =
  let src =
    io_ok ~what:"write source"
      (Soundml_io.read Nx.float32 (Io_corpus.bulk "wav-float32"))
  in
  List.map
    (fun (label, format, ext) ->
      let tmp =
        Filename.concat (Io_corpus.dir ()) ("write_tmp_" ^ label ^ ext)
      in
      Thumper.bench (Printf.sprintf "write %s 30s" label) (fun () ->
          io_ok ~what:label (Soundml_io.write ~format tmp src) ) )
    [ ("pcm16", Soundml_io.Format.create ~encoding:`Pcm_16 `Wav, ".wav")
    ; ("pcm24", Soundml_io.Format.create ~encoding:`Pcm_24 `Wav, ".wav")
    ; ("float32", Soundml_io.Format.create ~encoding:`Float32 `Wav, ".wav")
    ; ("flac", Soundml_io.Format.create ~encoding:`Pcm_16 `Flac, ".flac")
    ; ("ogg", Soundml_io.Format.create `Ogg, ".ogg") ]

let io_resample_benchmarks () =
  let bulk = Io_corpus.bulk "wav-float32" in
  List.concat_map
    (fun (pair, target) ->
      [ Thumper.bench (Printf.sprintf "read_resample %s 30s f32" pair) (fun () ->
            io_ok ~what:pair
              (Soundml_io.read ~sample_rate:target Nx.float32 bulk) )
      ; Thumper.bench (Printf.sprintf "read_plus_apply %s 30s f32" pair)
          (fun () ->
            let a = io_ok ~what:pair (Soundml_io.read Nx.float32 bulk) in
            let cfg =
              Soundml.Resample.Config.create
                ~sample_rate:a.Soundml_io.sample_rate ~target ()
            in
            Soundml.Resample.apply cfg a.Soundml_io.data ) ] )
    [("44k1-16k", 16000); ("44k1-48k", 48000)]

let io_benchmarks () =
  let (_ : string) = Io_corpus.ensure () in
  io_read_benchmarks () @ io_info_benchmarks () @ io_many_benchmarks ()
  @ io_write_benchmarks () @ io_resample_benchmarks ()

let () =
  exit
  @@ Nx.Rng.with_key (Nx.Rng.key 42)
  @@ fun () ->
  Thumper.run "soundml_io"
    ~budgets:
      [ Thumper.Budget.no_slower_than 0.05
      ; Thumper.Budget.no_more_alloc_than 0.01 ]
    [Thumper.group "io" (io_benchmarks ())]
