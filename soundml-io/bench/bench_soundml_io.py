"""Python cross-reference for the soundml-io benchmark rows.

The fair-fight side of the io gates: python-soundfile and librosa over the
SAME corpus files the thumper rows and the C ceiling harness read (the
corpus is generated by soundml-io's own writer — run
``dune exec bench/bench_soundml.exe -- --quick`` once to create it).

Fair fights, frozen: ``librosa.load(path, sr=None, mono=False)`` against
``Soundml_io.read`` (same native rate, same channels, float32 both sides);
``soundfile.read(dtype='float32')`` as the wrapper-stack reference and its
``out=`` form against the ``Reader.read ?out`` row; writes compare
close-to-close on both sides (no fsync anywhere). The resampled-read row
has no Python twin here by design: librosa's resampler is a different
algorithm, so that comparison would measure the resampler, not the I/O.

Discipline: warm cache (one untimed pass), gc disabled inside timed
regions, min-of-N primary statistic with the median as sanity.

Run: python bench/bench_soundml_io.py [corpus_dir]
Output: name,min_s,median_s rows (CSV) on stdout.
"""

from __future__ import annotations

import gc
import os
import sys
import time

import numpy as np
import soundfile as sf

try:
    import librosa
except ImportError:  # librosa rows are skipped, soundfile rows still run
    librosa = None

FAMILIES = ["wav-pcm16", "wav-pcm24", "wav-pcm32", "wav-float32", "flac", "ogg"]
MANY = ["wav-pcm16", "wav-float32", "flac"]
EXT = {"flac": "flac", "ogg": "ogg"}


def corpus_dir() -> str:
    if len(sys.argv) > 1:
        return sys.argv[1]
    env = os.environ.get("SOUNDML_IO_BENCH_CORPUS")
    if env:
        return env
    return os.path.join(
        os.environ.get("TMPDIR", "/tmp"), "soundml-io-bench-corpus-v2"
    )


def fam_path(root: str, fam: str, cell: str) -> str:
    ext = EXT.get(fam, "wav")
    return os.path.join(root, f"{fam}_{cell}.{ext}")


def measure(fn, n: int):
    """(min, median) seconds per call over n timed calls, one warm-up."""
    fn()
    times = []
    gc.disable()
    try:
        for _ in range(n):
            t0 = time.perf_counter_ns()
            fn()
            times.append(time.perf_counter_ns() - t0)
    finally:
        gc.enable()
    times.sort()
    return times[0] / 1e9, times[len(times) // 2] / 1e9


def emit(name: str, fn, n: int) -> None:
    mn, md = measure(fn, n)
    print(f"{name},{mn:.9f},{md:.9f}", flush=True)


def main() -> None:
    root = corpus_dir()
    probe = fam_path(root, "wav-pcm16", "22050_mo_1s")
    if not os.path.exists(probe):
        print(
            f"corpus not found at {root} — generate it first:\n"
            "  dune exec bench/bench_soundml.exe -- --quick",
            file=sys.stderr,
        )
        sys.exit(2)

    print("name,min_s,median_s")

    for fam in FAMILIES:
        small = fam_path(root, fam, "22050_mo_1s")
        bulk = fam_path(root, fam, "44100_st_30s")

        emit(
            f"sf_read_f32 {fam} 1s",
            lambda p=small: sf.read(p, dtype="float32"),
            200,
        )
        emit(
            f"sf_read_f32 {fam} 30s",
            lambda p=bulk: sf.read(p, dtype="float32"),
            30,
        )
        bulk_mono = fam_path(root, fam, "44100_mo_30s")
        emit(
            f"sf_read_f32 {fam} 30s-mo",
            lambda p=bulk_mono: sf.read(p, dtype="float32"),
            30,
        )

        with sf.SoundFile(bulk) as f:
            out = np.empty((f.frames, f.channels), dtype=np.float32)
        emit(
            f"sf_read_f32_out {fam} 30s",
            lambda p=bulk, o=out: sf.read(p, dtype="float32", out=o),
            30,
        )

        if librosa is not None:
            emit(
                f"librosa_fair {fam} 1s",
                lambda p=small: librosa.load(p, sr=None, mono=False),
                200,
            )
            emit(
                f"librosa_fair {fam} 30s",
                lambda p=bulk: librosa.load(p, sr=None, mono=False),
                30,
            )
            emit(
                f"librosa_fair {fam} 30s-mo",
                lambda p=bulk_mono: librosa.load(p, sr=None, mono=False),
                30,
            )

    for fam in ["wav-pcm16", "flac", "ogg"]:
        bulk = fam_path(root, fam, "44100_st_30s")

        def open_close(p=bulk):
            with sf.SoundFile(p):
                pass

        emit(f"sf_open_close {fam}", open_close, 300)

    for cls in MANY:
        paths = [
            line.strip()
            for line in open(os.path.join(root, "many", f"{cls}.list"))
            if line.strip()
        ]

        def sf_loop(ps=paths):
            for p in ps:
                sf.read(p, dtype="float32")

        emit(f"sf_many 1000x1s {cls}", sf_loop, 12)

        if librosa is not None:

            def lr_loop(ps=paths):
                for p in ps:
                    librosa.load(p, sr=None, mono=False)

            emit(f"librosa_many 1000x1s {cls}", lr_loop, 12)

    # writes: the 30 s stereo float32 payload, close-to-close. Ogg is
    # written in 65536-frame chunks — a one-shot multi-megaframe Vorbis
    # write segfaults libsndfile 1.2.2.
    data, sr = sf.read(fam_path(root, "wav-float32", "44100_st_30s"),
                       dtype="float32")
    for label, fmt, subtype, ext in [
        ("pcm16", "WAV", "PCM_16", "wav"),
        ("pcm24", "WAV", "PCM_24", "wav"),
        ("float32", "WAV", "FLOAT", "wav"),
        ("flac", "FLAC", "PCM_16", "flac"),
        ("ogg", "OGG", "VORBIS", "ogg"),
    ]:
        tmp = os.path.join(root, f"_py_write_tmp.{ext}")

        if label == "ogg":

            def wr(d=data, s=sr, t=tmp, f=fmt, st=subtype):
                with sf.SoundFile(
                    t, "w", samplerate=s, channels=d.shape[1], format=f,
                    subtype=st,
                ) as g:
                    for i in range(0, len(d), 65536):
                        g.write(d[i : i + 65536])

        else:

            def wr(d=data, s=sr, t=tmp, f=fmt, st=subtype):
                sf.write(t, d, s, format=f, subtype=st)

        emit(f"sf_write {label} 30s", wr, 12)
        os.unlink(tmp)


if __name__ == "__main__":
    main()
